/* USER CODE BEGIN 0 */
int SoftDeadzone(int value, int center, int dead, float expo, float max, float min) {
    int diff = value - center;
    int abs_diff = abs(diff);
    if (abs_diff <= dead) return 1500;
    int max_range = (diff > 0) ? (4095 - center - dead) : (center - dead - 10);
    if (max_range <= 0) return 1500;
    float normalized = (float)(abs_diff - dead) / max_range;
    if (normalized > 1.0f) normalized = 1.0f;
    float curved = powf(normalized, expo);
    float output;
    if (diff > 0) {
    	output = 1500.0f + (curved * (max - 1500.0f));
    } else {
    	output = 1500.0f - (curved * (1500.0f - min));
    }
    return (int)output;
}
